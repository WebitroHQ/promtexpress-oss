export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const locale = await getLocale();
  const messages = await getMessages();
  // <html lang> follows the rendered locale so screen readers + Google read
  // the correct language. Per D1 (2026-05-11) canonical/OG always point to EN
  // even on TR pages (handled in lib/seo/hreflang.ts), but lang must reflect
  // the visible language for accessibility correctness.
  const htmlLang = locale === "tr" ? "tr" : "en-US";
  return (
    <html
      lang={htmlLang}
      suppressHydrationWarning
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <head>
        {/* Plan §7.2 — preconnect to first-paint dependencies. Google Fonts
            preconnects removed (MOB-3): fonts are self-hosted via next/font,
            so those TLS connections were never used. */}
        <link rel="preconnect" href="https://static.cloudflareinsights.com" />
        <link rel="dns-prefetch" href="https://lh3.googleusercontent.com" />
        <link rel="dns-prefetch" href="https://cdn.paddle.com" />
      </head>
      <body className="min-h-full flex flex-col bg-bg text-text">
        {/* Plan §7.5 — skip-to-content link (a11y → SEO). */}
        <a
          href="#main-content"
          className="sr-only focus:not-sr-only focus:fixed focus:top-2 focus:left-2 focus:z-50 focus:px-4 focus:py-2 focus:bg-primary focus:text-primary-text focus:rounded-md focus:shadow-lg"
        >
          Skip to content
        </a>
        <JsonLd data={organizationSchema()} />
        <JsonLd data={websiteSchema()} />
        <NextIntlClientProvider locale={locale} messages={messages}>
        <SessionProvider>
          <ThemeProvider
            attribute="data-theme"
            defaultTheme="light"
            enableSystem
            disableTransitionOnChange
          >
            <PaddleProvider>
              {children}
              <Toaster />
              {/* Plan 2026-05-08 step 5 — analytics tracker is gated by user consent. */}
              <ConsentGate category="analytics">
                <Suspense fallback={null}>
                  <PageViewTracker />
                </Suspense>
              </ConsentGate>
              {/*
                Google Consent Mode v2 (Advanced).
                gtag is loaded for ALL users with default 'denied' signals;
                ConsentModeUpdater flips signals to 'granted' when the user
                accepts marketing/analytics cookies. Cookieless pings keep
                flowing in the meantime, recovering 15-25% attribution.
              */}
              <GoogleAdsTag />
              <ConsentModeUpdater />
              <CookieConsentBanner />
            </PaddleProvider>
          </ThemeProvider>
        </SessionProvider>
        </NextIntlClientProvider>
      </body>
    </html>
  );
}
