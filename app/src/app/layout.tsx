// Cookie-driven locale (NEXT_LOCALE) means cached HTML must not be reused
// across visitors with different locales. Force-dynamic guarantees a fresh
// render per request, which emits `Cache-Control: private, no-cache` — that
// is the actual safeguard preventing shared caches from leaking one locale's
// HTML to another visitor. (Note: a middleware-set `Vary: Cookie` is NOT
// relied upon — Next's RSC vary headers override it in the response pipeline;
// see src/proxy.ts cache-invariant note.) Trade-off: no Full Route Cache
// benefits at the root shell. The cost is acceptable for correct i18n;
// per-page static export can be reintroduced when a future PR moves to fully
// URL-based locales.
